/** 按前缀认境界, 因此 '筑基中期'、'筑基三层' 都能认出来 */
export function 查境界(境界: string) {
  for (const [名称, 数据] of _.entries(境界表)) {
    if (境界.startsWith(名称)) {
      return { 名称, ...数据 };
    }
  }
  return { 名称: '未明', 速率: 1, 上限: 3600, 描述: '境界未明。', 能力范围: '不可测度。' };
}

/** 下一个境界; 已经是大乘则返回 undefined */
export function 下一境界(境界: string) {
  const 位置 = 境界顺序.indexOf(查境界(境界).名称);
  return 位置 < 0 || 位置 >= 境界顺序.length - 1 ? undefined : 境界顺序[位置 + 1];
}

/** 纯修炼突破要多少年 (倍率按 1 算) */
export function 纯修年(境界: string): number {
  const 数据 = 查境界(境界);
  return _.round(数据.上限 / 数据.速率 / 一年日数, 1);
}

