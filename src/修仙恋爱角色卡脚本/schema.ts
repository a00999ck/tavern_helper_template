/**
 * 把变量里存的值拼成能直接塞进 `<img src>` 的地址.
 *
 * - 空 → 空字符串，界面自己退回水墨占位
 * - 已经是完整链接 / data URI / 以 `/` 开头 → 原样返回（想临时换图床也不必改这里）
 * - 其余一律当成文件名，补上 `.png` 再拼到 `素材源/<类别>/` 下
 */
export function 素材链接(值: string | undefined, 类别: '立绘' | '背景' | 'CG'): string {
  const 原值 = (值 ?? '').trim();
  if (原值 === '') {
    return '';
  }
  if (/^(https?:)?\/\//.test(原值) || 原值.startsWith('data:') || 原值.startsWith('/')) {
    return 原值;
  }
  const 文件 = /\.(png|jpe?g|webp|gif|avif|svg)$/i.test(原值) ? 原值 : `${原值}.png`;
  return `${素材源}/${类别}/${文件}`;
}

