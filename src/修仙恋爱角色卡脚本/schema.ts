/** 把数字写成汉字, 用于年份 (1~9999 够用了) */
function 中文数(数: number): string {
  const 数字 = '零一二三四五六七八九';
  const 位 = ['', '十', '百', '千'];
  const 串 = String(Math.max(0, Math.floor(数)));

  let 输出 = '';
  let 攒着零 = false;
  for (let i = 0; i < 串.length; i++) {
    const 值 = Number(串[i]);
    if (值 === 0) {
      攒着零 = true;
      continue;
    }
    if (攒着零 && 输出 !== '') {
      输出 += '零';
    }
    攒着零 = false;
    输出 += 数字[值] + 位[串.length - 1 - i];
  }
  // "一十二" 应当写成 "十二"
  return 输出.replace(/^一十/, '十');
}

/** 表单日 = 正月初一 */
export function 格式化历日(历日: number, 时段 = ''): string {
  const 总日 = Math.max(0, Math.floor(历日));
  const 年 = Math.floor(总日 / 一年日数) + 1;

  let 余 = 总日 % 一年日数;
  let 月 = 0;
  while (月 < 每月天数.length - 1 && 余 >= 每月天数[月]!) {
    余 -= 每月天数[月]!;
    月++;
  }

  return `大衍历${年 === 1 ? '元' : 中文数(年)}年 ${月名[月]}${日名[余]}${时段}`;
}

/** 把天数说成人话: 不足一年说日, 超过一年说年 */
export function 说时长(天数: number): string {
  if (天数 < 一年日数) {
    return `${_.round(天数, 1)}日`;
  }
  const 年 = Math.floor(天数 / 一年日数);
  const 余日 = _.round(天数 - 年 * 一年日数, 1);
  return 余日 > 0 ? `${年}年${余日}日` : `${年}年`;
}

/** 把大数字说成人话: 一万以上用「万」, 免得日志里一长串数不清的零 */
export function 说数值(数值: number): string {
  const 数 = _.round(数值, 1);
  if (Math.abs(数) < 10000) {
    return `${数}`;
  }
  return `${_.round(数 / 10000, 1)}万`;
}

