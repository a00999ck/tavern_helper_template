/**
 * 由主角与出场人物算出所有 `$` 派生值.
 *
 * schema 的 transform 与「世界推进」脚本都调用它, 因此两边算出来的永远一致 ——
 * 脚本改动境界后能立刻把新的速率、上限、描述一起补上, 不必等下一次解析.
 */
export function 算修行(主角: 主角变量, 人物: 人物变量) {
  const 境界 = 查境界(主角.境界);
  // 主修功法只有一门, 取倍率最高的那一门, 其余不叠加
  const 功法倍率 = _.max(_.map(主角.功法, '倍率')) ?? 1;
  // 双修倍率 = 1 + 所有双修对象按其好感度阶段给出的加成之和; 没有对象时恰为 1
  const 双修倍率 = _.round(
    1 +
      _.sum(
        _.map(主角.双修, (_值, 姓名) => _.get(双修加成, 好感阶段(_.get(人物, [姓名, '好感度'], 0)), 0)),
      ),
    2,
  );
  const 修炼倍率 = _.round(主角.灵根.倍率 * 功法倍率 * 双修倍率, 2);

  return {
    $境界描述: 境界.描述,
    $境界能力范围: 境界.能力范围,
    $境界速率: 境界.速率,
    $修为上限: 境界.上限,
    $纯修年: 纯修年(境界.名称),
    $双修倍率: 双修倍率,
    $修炼倍率: 修炼倍率,
    /** 每过一日, 修为应当增加多少 */
    $修为增速: _.round(境界.速率 * 修炼倍率, 2),
  };
}

