/**
 * 世界推进的**纯逻辑**, 与 MVU 事件无关, 因此可以直接拿来测.
 *
 * 每一轮按顺序做三件事 —— 顺序不能换, 因为跨区赶路的时间要算进修为主体例里:
 *
 *   1. **移动**: 对照地图校验大区/小区域, 若跨了大区就按 `跨区日数` 得出赶路天数
 *   2. **历日**: 历日 += 经过天数 + 赶路天数, 再把 经过天数 清零
 *   3. **修行**: 按时间逐境界推进修为, 满上限就突破, 再把结果写进日志
 *
 * @param variables 一份 MVU 变量表, 会被就地修改
 * @param 旧变量 上一轮的变量表, 用来判断"移动了没有"; 缺省则视为没有移动
 * @returns 写进 `世界._移动日志` 与 `主角._修行日志` 的两段文字
 */

/** 一段境界里修炼了多久、攒了多少修为 */
type 修炼段 = { 境界: string; 天数: number; 增量: number };

export function 结算(
  variables: Mvu.MvuData,
  旧变量?: Mvu.MvuData,
): { 移动: string; 修行: string; 际遇: string } {
  const 世界 = _.get(variables, 'stat_data.世界') as Record<string, any> | undefined;
  const 主角 = _.get(variables, 'stat_data.主角') as Parameters<typeof 算修行>[0] | undefined;
  if (!_.isObject(世界) || !_.isObject(主角)) {
    return { 移动: '', 修行: '', 际遇: '' };
  }
  const 人物 = _.get(variables, 'stat_data.人物', {});

  // --- 1. 移动 ---
  const { 日志: 移动日志, 赶路天数 } = 结算移动(世界, 旧变量);

  // --- 2. 历日 ---
  const 经过天数 = _.clamp(_.toNumber(世界.经过天数) || 0, 0, 365000);
  世界.经过天数 = 0;

  const 总天数 = _.round(经过天数 + 赶路天数, 2);
  世界.历日 = _.round((_.toNumber(世界.历日) || 0) + 总天数, 2);
  世界.$当前时间 = 格式化历日(世界.历日, _.toString(世界.时段));

  // --- 3. 修行 ---
  const { 日志: 修行日志, 境界, 修为, 派生 } = 结算修行(主角, 人物, 总天数);

  _.set(variables, 'stat_data.主角.境界', 境界);
  _.set(variables, 'stat_data.主角.修为', 修为);
  Object.assign(主角, 派生);
  _.set(variables, 'stat_data.主角._修行日志', 修行日志);
  _.set(variables, 'stat_data.世界._移动日志', 移动日志);

  // --- 4. 际遇: 有人好感跨档, 记一笔待写的事件, 之后每轮催到写完为止 ---
  const 际遇日志 = 结算际遇(人物, 世界, 旧变量);
  世界._际遇日志 = 际遇日志;

  return { 移动: 移动日志, 修行: 修行日志, 际遇: 际遇日志 };
}

/**
 * 比对每个人的好感度档位与「她这辈子到过的最高档位」(`_已达阶段`), 把跨档记成一笔**待写的事件**.
 *
 * 跨档是**一次性事件**: 只有当前档位高过 `_已达阶段` 才算数, 记下后立刻把它抬到新档位.
 * 于是好感掉下去再涨回来不会重复演同一场; 而开局就在高档位的人（比如大乘的母亲）,
 * 她那些低档的事件永远不会触发 —— 那些图可以干脆不画.
 *
 * 两种情况只对齐、不触发: 还没轮到她登场（旧变量里没有这个人）,
 * 以及 `_已达阶段` 还是空的（老存档、或者刚加上这个字段）.
 *
 * ## 为什么脚本不直接换场面画
 *
 * 是因为**对不齐**. 脚本在这一轮末尾才知道"跨档了", 但这一轮的正文早就写完了 ——
 * 脚本这时候把 CG 换上, 就会出现"图已经挂在那儿、正文却还没写到"的一轮错位.
 * 所以改成: 脚本只记一笔、然后**每轮都催**, 直到 AI 把 `世界.CG` 设成同名的
 * 「姓名·档位」为止 —— 那表示它这一轮正在写这一场, 图和文就落在同一轮里.
 *
 * @returns 写进 `世界._际遇日志` 的那段文字
 */
function 结算际遇(人物: Record<string, any>, 世界: Record<string, any>, 旧变量?: Mvu.MvuData): string {
  const 旧人物 = _.get(旧变量 ?? {}, 'stat_data.人物', {});
  const 待写 = (_.isObject(世界._待写事件) ? 世界._待写事件 : (世界._待写事件 = {})) as Record<string, string>;

  // AI 把 世界.CG 设成同名了, 说明它已经在写这一场 —— 划掉
  const 已动笔 = _.toString(世界.CG);
  if (已动笔 !== '' && _.has(待写, 已动笔)) {
    _.unset(待写, 已动笔);
  }

  // 本轮新跨的档记进来
  const 新跨: string[] = [];
  for (const [姓名, 人] of _.entries(人物)) {
    const 新值 = _.toNumber(_.get(人, '好感度'));
    if (!_.isFinite(新值)) {
      continue;
    }
    const 新阶段 = 好感阶段(新值);
    const 已达 = _.toString(_.get(人, '_已达阶段', ''));

    if (!_.has(旧人物, 姓名) || 已达 === '') {
      人._已达阶段 = 新阶段;
      continue;
    }
    if (阶段序(新阶段) > 阶段序(已达)) {
      const 键 = `${姓名}·${新阶段}`;
      人._已达阶段 = 新阶段;
      if (!_.has(待写, 键)) {
        待写[键] = 姓名;
        新跨.push(键);
      }
    }
  }

  const 全部 = _.keys(待写);
  if (全部.length === 0) {
    return '【际遇】当前没有待写的跨档事件。';
  }

  const 抬头 = 新跨.length > 0 ? `刚刚跨档：${新跨.join('、')}。` : '';
  const 点名 = 全部.map(键 => `「${键}」`).join('、');

  return (
    `【际遇】${抬头}还欠 ${全部.length} 场戏：${点名}。\n` +
    '这是**必写项**：她们各自条目里那一档的「跨进这一档的事件」已经写死了这一场。\n' +
    '- 照着写，一个字都不用改；不要另编、不要换一个更清淡的场面\n' +
    '- 不要用"一夜过去""此处省略""自然是一夜无话"这类写法带过，也不要收在拥抱就停\n' +
    '- 按 文风 完整写出来（甜腻、贴身体反应、把修仙的词挪来写情）\n' +
    '写完把 世界.CG 设成对应的「姓名·档位」再清空正文以外的东西 —— ' +
    '场面画跟着正文走，你设了脚本才会把这一条划掉。'
  );
}

/** 对照地图校验当前位置, 并算出跨区赶路要几天; `世界` 是变量表里的那一份, 直接改它即可 */
function 结算移动(世界: Record<string, any>, 旧变量?: Mvu.MvuData): { 日志: string; 赶路天数: number } {
  const 旧世界 = _.get(旧变量 ?? {}, 'stat_data.世界');
  const 旧大区 = _.isObject(旧世界) ? _.toString(_.get(旧世界, '当前大区')) : '';
  const 旧地点 = _.isObject(旧世界) ? _.toString(_.get(旧世界, '当前地点')) : '';

  const 修正: string[] = [];

  // 大区必须是地图上写着的
  let 大区 = _.toString(世界.当前大区);
  if (查小区域(大区) === undefined) {
    大区 = 查小区域(旧大区) !== undefined ? 旧大区 : _.keys(地图)[0]!;
    修正.push(`「${世界.当前大区}」不在地图上，已退回 ${大区}`);
    世界.当前大区 = 大区;
  }

  // 小区域必须属于所在大区
  const 合法地点 = 查小区域(大区)!;
  let 地点 = _.toString(世界.当前地点);
  if (!合法地点.includes(地点)) {
    修正.push(`「${地点}」不是 ${大区} 的地方，已改为 ${合法地点[0]}`);
    地点 = 合法地点[0]!;
    世界.当前地点 = 地点;
  }

  const 备注 = 修正.length > 0 ? `（${修正.join('；')}）` : '';

  if (旧大区 === '') {
    return { 日志: `【移动】当前位于 ${大区} · ${地点}。${备注}`, 赶路天数: 0 };
  }
  if (旧大区 === 大区 && 旧地点 === 地点) {
    return { 日志: `【移动】本轮未移动，仍在 ${大区} · ${地点}。${备注}`, 赶路天数: 0 };
  }
  if (旧大区 === 大区) {
    return { 日志: `【移动】${大区} · ${旧地点} → ${地点}，同区走动不耗时。${备注}`, 赶路天数: 0 };
  }

  const 赶路天数 = 跨区耗时(旧大区, 大区);
  return {
    日志:
      `【移动】${旧大区} · ${旧地点} → ${大区} · ${地点}，跨区赶路 ${说时长(赶路天数)}` +
      `（这段时间已由脚本自动计入本轮）。${备注}`,
    赶路天数,
  };
}

/**
 * 修为结算.
 *
 * **按时间推进**, 而不是拿当前速率乘总天数 —— 因为境界中途会变, 速率也跟着变:
 * 每进入一个境界, 先算"攒满上限还要几天"; 剩余时间够就扣掉这些天突破, 带着剩下的
 * 时间进入下一境界; 不够就按当前速率累积这剩下的几天. 这样时间与修为都不会被凭空吞掉.
 * 境界链是有限的 (炼气→…→大乘), 所以跳过再长的时间也会自然收敛.
 */
function 结算修行(主角: Parameters<typeof 算修行>[0], 人物: Parameters<typeof 算修行>[1], 总天数: number) {
  const 起点境界 = 查境界(_.toString(主角.境界)).名称;
  let 境界 = 起点境界;
  let 修为 = _.clamp(_.toNumber(主角.修为) || 0, 0, Number.MAX_SAFE_INTEGER);
  let 派生 = 算修行(主角, 人物);

  const 轨迹: 修炼段[] = [];
  const 突破: string[] = [];
  let 剩余 = 总天数;
  let 段天数 = 0;
  let 段起点 = 修为;

  /** 记下"刚离开的这个境界"修炼了多久、涨了多少 */
  const 收段 = () => {
    if (段天数 > 0 || 轨迹.length === 0) {
      轨迹.push({ 境界, 天数: _.round(段天数, 2), 增量: _.round(修为 - 段起点, 2) });
    }
  };

  for (;;) {
    const 上限 = 派生.$修为上限;
    const 增速 = 派生.$修为增速;

    // 攒满 (包括上一轮留下的、或者刚好卡在上限的) 就突破
    if (修为 >= 上限) {
      收段();
      const 下个 = 下一境界(境界);
      if (下个 === undefined) {
        // 已至大乘, 修为封顶, 再多的时间也无处可用
        修为 = 上限;
        break;
      }
      修为 = _.round(修为 - 上限, 2);
      境界 = 下个;
      突破.push(境界);
      派生 = 算修行({ ...主角, 境界 }, 人物);
      段起点 = 修为;
      段天数 = 0;
      continue;
    }

    if (剩余 <= 0 || 增速 <= 0) {
      收段();
      break;
    }

    const 攒满还需 = (上限 - 修为) / 增速;
    if (攒满还需 > 剩余) {
      修为 = _.round(修为 + 增速 * 剩余, 2);
      段天数 += 剩余;
      收段();
      break;
    }

    剩余 = _.round(剩余 - 攒满还需, 2);
    段天数 += 攒满还需;
    修为 = 上限;
  }

  修为 = _.round(_.clamp(修为, 0, 派生.$修为上限), 2);

  return { 日志: 写修行日志({ 总天数, 轨迹, 突破, 修为, 上限: 派生.$修为上限, 境界 }), 境界, 修为, 派生 };
}

function 写修行日志({
  总天数,
  轨迹,
  突破,
  修为,
  上限,
  境界,
}: {
  总天数: number;
  轨迹: 修炼段[];
  突破: string[];
  修为: number;
  上限: number;
  境界: string;
}): string {
  const 进度 = `${说数值(修为)}/${说数值(上限)}`;

  if (总天数 <= 0) {
    return `【修行推进】本轮未经过时间，修为保持 ${进度}。`;
  }

  // 炼气(1年) → 筑基(3.1年) → 金丹(4.2年)，让 AI 一眼看出每一境各修了多久
  // 抹掉不足一日的零头, 免得日志里出现 "元婴(0.01日)" 这种噪声
  const 有效 = 轨迹.filter(段 => 段.天数 >= 0.05);
  const 经过 = (有效.length > 0 ? 有效 : 轨迹).map(段 => `${段.境界}(${说时长(段.天数)})`).join(' → ');
  const 尾巴 =
    突破.length > 0
      ? `突破 ${突破.join(' → ')}，现 ${进度}`
      : 境界 === '大乘' && 修为 >= 上限
        ? `已至大乘，修为封顶于 ${进度}`
        : `现 ${进度}`;

  return `【修行推进】经过 ${说时长(总天数)}：${经过}。${尾巴}。`;
}
